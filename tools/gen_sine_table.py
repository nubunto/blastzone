#!/usr/bin/env python3
"""Generates the Q32.32 quarter-wave sine table used by FixedMath (ADR 0004).

The table is generated offline so the Simulation never computes a float at run time.
Entries are sin(i * (pi/2) / STEPS) rounded to the nearest 2^-32, using exact decimal
arithmetic so the output does not depend on the host's floating-point library.

Usage: python3 tools/gen_sine_table.py > src/Blastzone.Simulation/Numerics/QuarterSineTable.g.cs
"""
from decimal import Decimal, getcontext, ROUND_HALF_EVEN

STEPS = 4096
getcontext().prec = 80
PI = Decimal("3.14159265358979323846264338327950288419716939937510582097494459230781640628620899")
SCALE = Decimal(2 ** 32)


def sin(x: Decimal) -> Decimal:
    # Taylor series; x <= pi/2 converges quickly at 80 digits.
    term, total, n = x, x, 1
    while True:
        term = -term * x * x / ((2 * n) * (2 * n + 1))
        if abs(term) < Decimal(10) ** -70:
            return total
        total += term
        n += 1


values = []
for i in range(STEPS + 1):
    v = sin(PI / 2 * i / STEPS) * SCALE
    values.append(int(v.quantize(Decimal(1), rounding=ROUND_HALF_EVEN)))
assert values[0] == 0 and values[-1] == 2 ** 32

print("// <auto-generated> by tools/gen_sine_table.py. Do not edit by hand. </auto-generated>")
print("using System;")
print()
print("namespace Blastzone.Simulation.Numerics;")
print()
print("public static partial class FixedMath")
print("{")
print(f"    /// <summary>sin(i * (pi/2) / {STEPS}) for i in 0..{STEPS}, as Q32.32 raw values.</summary>")
print("    public static ReadOnlySpan<long> QuarterSineTable =>")
print("    [")
for i in range(0, len(values), 8):
    print("        " + ", ".join(str(v) for v in values[i:i + 8]) + ",")
print("    ];")
print("}")
